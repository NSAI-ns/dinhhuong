/**
 * Render thanh phân trang
 */
function renderSchoolPagination(totalItems, itemsPerPage, currentPage) {
  const container = document.getElementById('schoolPagination');
  if (!container) return;

  const totalPages = Math.ceil(totalItems / itemsPerPage);
  if (totalPages <= 1) {
    container.innerHTML = '';
    return;
  }

  let html = `
    <button
      type="button"
      class="page-btn"
      ${currentPage === 1 ? 'disabled' : ''}
      onclick="goToSchoolPage(${currentPage - 1})"
      title="Trang trước"
    >
      « Trước
    </button>
  `;

  // Hiển thị các số trang thông minh
  const pageNumbers = [];
  if (totalPages <= 7) {
    for (let i = 1; i <= totalPages; i++) pageNumbers.push(i);
  } else {
    pageNumbers.push(1);
    if (currentPage > 3) pageNumbers.push('...');
    const start = Math.max(2, currentPage - 1);
    const end = Math.min(totalPages - 1, currentPage + 1);
    for (let i = start; i <= end; i++) pageNumbers.push(i);
    if (currentPage < totalPages - 2) pageNumbers.push('...');
    pageNumbers.push(totalPages);
  }

  pageNumbers.forEach(p => {
    if (p === '...') {
      html += `<span class="page-ellipsis">...</span>`;
    } else {
      html += `
        <button
          type="button"
          class="page-btn ${p === currentPage ? 'active' : ''}"
          onclick="goToSchoolPage(${p})"
        >
          ${p}
        </button>
      `;
    }
  });

  html += `
    <button
      type="button"
      class="page-btn"
      ${currentPage === totalPages ? 'disabled' : ''}
      onclick="goToSchoolPage(${currentPage + 1})"
      title="Trang sau"
    >
      Sau »
    </button>
  `;

  container.innerHTML = html;
}

